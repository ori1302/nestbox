#!/usr/bin/env python3
"""Builds engine/screen/font_data.cpp: the pet's text font, DejaVu Sans Bold drawn without smoothing (sharp
pixels) at three sizes whose capitals are 7, 10 and 15 px tall. One bit per pixel, printable ASCII.
The device never reads a font file; this runs once on a computer with Pillow.

    python3 tools/fontgen.py /path/to/DejaVuSans-Bold.ttf

DejaVu fonts are free to use and redistribute (the Bitstream Vera licence, engine/screen/FONT-LICENSE.txt).
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = {1: 10, 2: 14, 3: 20}            # engine text size -> font pixels (capitals 7, 10, 15 px)
FIRST, LAST = 32, 126

if len(sys.argv) < 2:
    sys.exit(__doc__)
path = sys.argv[1]
out = ['// Generated by tools/fontgen.py from DejaVu Sans Bold (see FONT-LICENSE.txt). Do not edit.',
       '#include "screen/font.h"', '', 'namespace nestbox {', '', 'namespace {']
tables = []
for size, px in SIZES.items():
    font = ImageFont.truetype(path, px)
    ascent, _ = font.getmetrics()

    def ink(text):
        im = Image.new('1', (px * 3, px * 3))
        d = ImageDraw.Draw(im)
        d.fontmode = '1'
        d.text((px, px), text, font=font, fill=1)
        return im, im.getbbox()
    _, cap_box = ink('H')
    cap_top = cap_box[1]                  # the top of the capitals: y = 0 for the engine
    base = cap_box[3]                     # the baseline row (just below the capitals)
    _, low = ink('gjpqy')
    desc = low[3] - base
    bits, glyphs = [], []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        im, box = ink(ch)
        if not box:
            glyphs.append((adv, 0, 0, 0, 0, len(bits)))
            continue
        x0, y0, x1, y1 = box
        w, h = x1 - x0, y1 - y0
        start = len(bits)
        for y in range(y0, y1):
            row = 0
            for x in range(x0, x1):
                if im.getpixel((x, y)):
                    row |= 1 << (x - x0)
            for k in range((w + 7) // 8):
                bits.append((row >> (8 * k)) & 255)
        glyphs.append((adv, x0 - px, y0 - cap_top, w, h, start))
    cap = base - cap_top
    name = f'S{size}'
    out.append(f'const uint8_t {name}_BITS[] = {{')
    for i in range(0, len(bits), 24):
        out.append('    ' + ', '.join(str(b) for b in bits[i:i + 24]) + ',')
    out.append('};')
    out.append(f'const Glyph {name}_GLYPHS[] = {{   // advance, x, y (from the top of the capitals), w, h, bits')
    for g in glyphs:
        out.append('    {%d, %d, %d, %d, %d, %d},' % g)
    out.append('};')
    tables.append((size, px, cap, desc, name))
out.append('}  // namespace')
out.append('')
out.append('const FontSize& font_size(int size) {')
out.append('    static const FontSize sizes[] = {')
for size, px, cap, desc, name in tables:
    pitch = cap + desc + max(2, cap // 3)
    out.append(f'        {{{size}, {cap}, {desc}, {pitch}, {name}_GLYPHS, {name}_BITS}},   // {px} px')
out.append('    };')
out.append('    return sizes[size <= 1 ? 0 : size >= 3 ? 2 : 1];')
out.append('}')
out.append('')
out.append('}  // namespace nestbox')
out.append('')
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'engine', 'screen', 'font_data.cpp')
open(dst, 'w').write('\n'.join(out))
print('wrote', os.path.normpath(dst), [(s, f'{p} px', f'caps {c}', f'below {d}') for s, p, c, d, _ in tables])
