#!/usr/bin/env python3
"""Builds engine/util/tzdata.cpp: every IANA time zone name a phone may send, with its POSIX TZ rule (the footer
line of the compiled zoneinfo file), so the device can apply summer time without a zone database.
Run on a Mac or Linux with /usr/share/zoneinfo:  python3 tools/tzdata.py"""
import os

ROOT = '/usr/share/zoneinfo'
SKIP_TOP = {'posix', 'right', 'Etc', 'SystemV', 'US', 'Canada', 'Mexico', 'Brazil', 'Chile'}


def footer(path):
    data = open(path, 'rb').read()
    if not data.startswith(b'TZif') or data[4:5] < b'2':
        return None
    lines = data.rstrip(b'\n').rsplit(b'\n', 1)
    return lines[1].decode() if len(lines) == 2 and lines[1] else None


zones = {}
for dirpath, dirs, files in os.walk(ROOT):
    rel = os.path.relpath(dirpath, ROOT)
    top = rel.split(os.sep)[0]
    if top in SKIP_TOP:
        dirs[:] = []
        continue
    for f in files:
        name = f if rel == '.' else rel + '/' + f
        if '/' not in name and name not in ('UTC', 'GMT'):
            continue                      # legacy top-level aliases (EST5EDT, Japan...) that phones don't send
        rule = footer(os.path.join(dirpath, f))
        if rule:
            zones[name] = rule
# Phones also send these.
for n in ('Etc/UTC', 'Etc/GMT'):
    zones[n] = 'UTC0'

out = ['// Generated by tools/tzdata.py from the system zoneinfo: IANA name -> POSIX TZ rule. Do not edit.',
       '#include "util/tzdata.h"', '#include <cstring>', '', 'namespace nestbox {', '', 'namespace {',
       'struct Zone { const char* name; const char* rule; };',
       'const Zone ZONES[] = {']
for n in sorted(zones):
    out.append('    {"%s", "%s"},' % (n, zones[n]))
out += ['};', '}  // namespace', '',
        'const char* posix_tz(const std::string& iana) {',
        '    size_t lo = 0, hi = sizeof ZONES / sizeof ZONES[0];',
        '    while (lo < hi) {',
        '        size_t mid = (lo + hi) / 2;',
        '        int c = std::strcmp(ZONES[mid].name, iana.c_str());',
        '        if (c == 0) return ZONES[mid].rule;',
        '        if (c < 0) lo = mid + 1; else hi = mid;',
        '    }',
        '    return nullptr;',
        '}', '', '}  // namespace nestbox', '']
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'engine', 'util', 'tzdata.cpp')
with open(dst, 'w') as f:
    f.write('\n'.join(out))
print(len(zones), 'zones,', sum(len(k) + len(v) + 2 for k, v in zones.items()), 'bytes of strings')
